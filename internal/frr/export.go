// Package frr produces gateway-side configuration without changing either end.
package frr

import (
	"errors"
	"fmt"
	"net/netip"
	"strings"
	"surge-controller/internal/config"
)

type Request struct {
	PeerID            string `json:"peer_id"`
	GatewayASN        uint32 `json:"gateway_asn"`
	GatewayRouterID   string `json:"gateway_router_id"`
	ControllerAddress string `json:"controller_address"`
}
type Export struct {
	Filename string   `json:"filename"`
	Content  string   `json:"content"`
	Warnings []string `json:"warnings"`
}

func Generate(d config.Document, input Request) (Export, error) {
	s := d.Settings
	local, err := netip.ParseAddr(input.ControllerAddress)
	routerID, re := netip.ParseAddr(input.GatewayRouterID)
	if err != nil || local.Zone() != "" || local.IsUnspecified() || local.IsMulticast() || local.IsLoopback() || local.IsLinkLocalUnicast() || re != nil || !routerID.Is4() || routerID.IsUnspecified() || routerID.IsMulticast() {
		return Export{}, errors.New("请填写 Mac 的可达地址和 对端 的 IPv4 Router ID")
	}
	if input.GatewayASN == 0 || s.BGP.LocalASN == 0 || s.BGP.ListenPort < 1 || s.BGP.ListenPort > 65535 || s.BGP.RouteLimit < 1 || s.BGP.RouteLimit > 128 {
		return Export{}, errors.New("请填写有效的 对端 ASN，并检查 RoutePilot 的 ASN、BGP 端口和路由上限")
	}
	source := s.DNS.Source4
	if local.Is6() {
		source = s.DNS.Source6
	}
	if source != local.String() {
		return Export{}, errors.New("Mac 邻居地址必须与已配置的对应地址族出口源地址一致")
	}
	hold, keep := s.BGP.HoldSeconds, s.BGP.KeepaliveSeconds
	if input.PeerID != "" {
		found := false
		for _, peer := range d.Peers {
			if peer.ID != input.PeerID {
				continue
			}
			found = true
			peerAddress, e := netip.ParseAddr(peer.Address)
			if e != nil || peerAddress.Is4() != local.Is4() || peer.ASN != input.GatewayASN {
				return Export{}, errors.New("导出的 对端 ASN 或地址族与所选 BGP 邻居不一致")
			}
			if peer.Port != 0 && peer.Port != 179 {
				return Export{}, errors.New("导出配置使用对端 TCP 179；请先把对应邻居端口改为 179")
			}
			if peer.HoldSeconds != 0 {
				hold, keep = peer.HoldSeconds, peer.KeepaliveSeconds
			}
		}
		if !found {
			return Export{}, errors.New("所选 BGP 邻居已不存在，请刷新后重试")
		}
	}
	if hold < 3 || hold > 65535 || keep < 1 || keep >= hold {
		return Export{}, errors.New("请检查 BGP Keepalive 和 Hold time")
	}
	r := s.Routing.Effective()
	dynamicImports := r.Mode != "static"
	var b strings.Builder
	fmt.Fprintf(&b, "! Generated by RoutePilot for the FRR peer device.\n! Peer ASN %d; RoutePilot ASN %d; RoutePilot address %s.\n! Accept all routes from this RoutePilot neighbor, bounded by maximum-prefix; export no routes back to RoutePilot.\n! Preserve advertised next hops; do not add next-hop-self.\n! Uploading is an operator action.\nrouter bgp %d\n bgp router-id %s\n no bgp default ipv4-unicast\n neighbor %s remote-as %d\n neighbor %s description RoutePilot\n neighbor %s timers %d %d\n", input.GatewayASN, s.BGP.LocalASN, local, input.GatewayASN, routerID, local, s.BGP.LocalASN, local, local, keep, hold)
	if s.BGP.ListenPort != 179 {
		fmt.Fprintf(&b, " neighbor %s port %d\n", local, s.BGP.ListenPort)
	}
	for _, ipv4 := range []bool{true, false} {
		if !ipv4 && !dynamicImports {
			continue
		}
		family, suffix := "ipv4", "V4"
		if !ipv4 {
			family, suffix = "ipv6", "V6"
		}
		fmt.Fprintf(&b, " address-family %s unicast\n  neighbor %s activate\n  neighbor %s route-map RP-IN-%s in\n  neighbor %s route-map RP-OUT out\n  neighbor %s maximum-prefix %d\n exit-address-family\n", family, local, local, suffix, local, local, s.BGP.RouteLimit)
	}
	b.WriteString("exit\n!\n") // Keep prefix lists and maps outside the BGP configuration section.
	for _, ipv4 := range []bool{true, false} {
		if !ipv4 && !dynamicImports {
			continue
		}
		suffix := "V4"
		if !ipv4 {
			suffix = "V6"
		}
		if dynamicImports {
			fmt.Fprintf(&b, "route-map RP-IN-%s permit 10\nexit\n!\n", suffix)
			continue
		}
		kind, any := "ip", "0.0.0.0/0 le 32"
		if !ipv4 {
			kind, any = "ipv6", "::/0 le 128"
		}
		fmt.Fprintf(&b, "%s prefix-list RP-PREFIXES-%s seq 10 deny %s\nroute-map RP-IN-%s permit 10\n match %s address prefix-list RP-PREFIXES-%s\nexit\nroute-map RP-IN-%s deny 100\nexit\n!\n", kind, suffix, any, suffix, kind, suffix, suffix)
	}
	b.WriteString("route-map RP-OUT deny 10\nexit\n")
	warnings := []string{"请在对端设备手动应用 FRR 配置，并合并已有邻居和策略；文件不会自动修改网关。", "导出不代表 BGP 已启用、邻居已建立或路由已安装。", "对端会接受此 RoutePilot 邻居发送的全部 IPv4/IPv6 前缀，并按 maximum-prefix 限制数量；请只连接可信的 RoutePilot 邻居。", "单网口上游 DNS 的源地址绕行策略仍需单独配置。"}
	if !r.UsesBGP() || !s.BGP.Enabled {
		warnings = append(warnings, "当前 BGP 未运行；切换 BGP/Hybrid 并启用 BGP 后才能建立邻居。")
	}
	if r.Mode == "static" {
		warnings = append(warnings, "当前为 Static 模式，对端会建立邻居但拒收路由；启用 BGP/Hybrid 后请重新导出并应用配置。")
	}
	if input.PeerID == "" {
		warnings = append(warnings, "尚未选择 RoutePilot 邻居；请在 RoutePilot 添加 对端 地址及该对端 ASN。")
	}
	return Export{Filename: "routepilot-frr.conf", Content: b.String(), Warnings: warnings}, nil
}
